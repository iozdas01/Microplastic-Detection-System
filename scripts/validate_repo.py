#!/usr/bin/env python3
"""Fail the commit when a fact has drifted from its single author.

This repo's design rule is: one fact, one author; everything read first is generated
from those authors. That rule was already written down before this file existed, and
it was violated in five places simultaneously, silently, for weeks — because nothing
checked. A design that depends on people noticing is not a design.

Each check below exists because a specific thing actually broke:

  1. brief-fresh   BRIEF.md's recorded source hashes still match the sources.
                   (The artifact read first must never be older than what it summarises.)
  2. state-prose   No current-state assertion in prose under reports/.
                   (hunch-lineage.md claimed "H004 (active)" for a day after H004 was
                   folded into an offering, while its own frontmatter said H003.)
  3. vocab         Every governed enum value is declared in schemas/vocabularies.yaml.
                   ("evidence" had three incompatible vocabularies; hunch status had two
                   undeclared values in the live file.)
  4. skill-desc    No skill body says SUPERSEDED while its description advertises it as
                   live. (startup-generate-dashboard did exactly this; the description is
                   the only part read before the routing decision.)
  5. routing       Every skill named in CLAUDE.md's routing table exists.
                   (It routed architecture work to /brainstorming, which does not exist.)
  6. generated     No hand-edit of a generated file.

Usage:
    python3 scripts/validate_repo.py            # all checks
    python3 scripts/validate_repo.py --fix-hint # print the command that fixes each failure

Exit 0 clean, 1 on any violation.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
VOCAB_FILE = ROOT / "schemas" / "vocabularies.yaml"

sys.path.insert(0, str(ROOT))
from scripts.idea import DATED_PART  # noqa: E402 — dated vs living has one author

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required: pip3 install -r requirements.txt")


# Fields whose values are governed by a vocabulary, and where they may appear.
# Only fields with a CLOSED value set belong here — a field that legitimately takes
# free text must not be listed, or the check becomes noise people learn to ignore.
GOVERNED = {
    "01-ideation/hunch-lineage.md": {
        "status": "hunch_status",
        "validation_status": "hunch_validation_status",
    },
    "02-assumptions/graph.md": {
        "status": "assumption_status",
        "category": "assumption_category",
        "lens": "lens",
        "validation_track": "validation_track",
        "quadrant": "quadrant",
        "importance": "importance",
    },
    "03-validation/evidence.md": {
        "verdict": "verdict",
        "source_type": "evidence_source_type",
    },
    "outreach/contacts.md": {
        "signal_type": "signal_type",
        "contact_role": "contact_role",
        "outcome_modifier": "outcome_modifier",
    },
}

LEDGERS = {
    "03-validation/evidence.md": re.compile(r"^  - id: (E\w+)\s*$", re.M),
    "02-assumptions/graph.md": re.compile(r"^  - id: ((?:H\d+)?A\w+)\s*$", re.M),
    "outreach/contacts.md": re.compile(r"^id: (C\w+)\s*$", re.M),
}

# Where an E-id is cited as a structured reference rather than mentioned in prose.
# Prose mentions are deliberately NOT checked: a dated snapshot may legitimately
# discuss an entry that has since been deleted.
CITE_BLOCK = re.compile(r"^    evidence_(?:for|against):\s*$")
CITE_END = re.compile(r"^(?:  - id:|    [a-z_]+:)")
OFFERING_CITE = re.compile(r"^\s*evidence:\s*\[([^\]]*)\]", re.M)


# Prose that asserts *current* state. State belongs in frontmatter or a `status:` field.
STATE_PROSE = re.compile(
    r"(?:^##+ .*—\s*(?:ACTIVE|RETIRED|KILLED|SUPERSEDED|FOLDED)\b"
    r"|\bis now \*\*[A-Z]\d+"
    r"|\bcurrently the active\b)",
    re.M,
)

GENERATED_MARKER = "GENERATED by scripts/"


def _vocab():
    # The registry is the root authority for every other check, so a malformed one is
    # fatal rather than a finding — but it must say so in one line, not a traceback.
    try:
        data = yaml.safe_load(VOCAB_FILE.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as e:
        sys.exit("FATAL: schemas/vocabularies.yaml does not parse — every other check "
                 "depends on it.\n%s" % e)
    out = {}
    for name, spec in (data.get("vocabularies") or {}).items():
        values = spec.get("values") if isinstance(spec, dict) else None
        if isinstance(values, dict):
            out[name] = {str(k) for k in values}
        elif isinstance(values, list):
            out[name] = {str(v) for v in values}
    return out


def _slugs():
    if not REPORTS.is_dir():
        return []
    return sorted(p.name for p in REPORTS.iterdir() if p.is_dir())


def _frontmatter_span(text: str):
    """Character range of the leading YAML frontmatter, or (0, 0)."""
    if not text.startswith("---"):
        return 0, 0
    end = text.find("\n---", 3)
    return (0, end + 4) if end != -1 else (0, 0)


