def main() -> int:
    show_hint = "--fix-hint" in sys.argv
    errors = []
    for _name, fn in CHECKS:
        fn(errors)

    if not errors:
        print("Repo valid: %d checks, %d ideas." % (len(CHECKS), len(_slugs())))
        return 0

    by_check = {}
    for name, msg, hint in errors:
        by_check.setdefault(name, []).append((msg, hint))

    print("Repo validation failed (%d issue(s)):\n" % len(errors))
    for name, items in by_check.items():
        print("[%s]" % name)
        for msg, hint in items:
            print("  - %s" % msg)
            if show_hint and hint:
                print("    → %s" % hint)
        print("")
    if not show_hint:
        print("Rerun with --fix-hint for the fix for each.")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
